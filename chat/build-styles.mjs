import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import config from "./tailwind.config.cjs";

const input = new URL("./styles.input.css", import.meta.url);
const result = await postcss([tailwindcss(config)]).process(await readFile(input, "utf8"), { from: fileURLToPath(input) });
const sheet = postcss.parse(result.css);
sheet.walkRules((rule) => {
  if (rule.parent.type === "atrule" && rule.parent.name.endsWith("keyframes")) return;
  if (!rule.selector.includes(".chatticus-chat")) rule.selectors = rule.selectors.map((selector) => `.chatticus-chat ${selector}`);
});
sheet.walkAtRules("keyframes", (rule) => { rule.params = `chatticus-chat-${rule.params}`; });
sheet.walkDecls("animation", (decl) => { decl.value = decl.value.replace(/\bpulse\b/g, "chatticus-chat-pulse"); });
await writeFile(new URL("./styles.css", import.meta.url), `/* Generated by npm run build:chat-styles; scoped to .chatticus-chat. */\n${sheet.toString().trimEnd()}\n`);
